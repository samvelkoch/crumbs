export function pick(arr, seed = Date.now()) {
  return arr[Math.abs(Math.floor(seed)) % arr.length];
}

// Реплика по ситуации дня: сначала то, что важно сейчас, иначе случайный совет
export function contextTip(ctx, seed) {
  const { hour, waterToday, mealsToday, skinToday, plate, radar } = ctx;
  if (plate === 4) return ['pusya', 'Сегодня супер-тарелка! Все четыре клетки собраны. Медок аплодирует иголками.', 'cheer'];
  if (radar?.suspects?.length && seed % 3 === 0) {
    return ['medok', 'На Радаре появился след. Загляни на вкладку «Радар», там всё по фактам.', 'think'];
  }
  if (hour >= 18 && !skinToday) return ['medok', 'Вечерний осмотр ещё не сделан. Два касания, и Радар станет точнее.', 'calm'];
  if (hour >= 11 && waterToday === 0) return ['pusya', 'Сегодня ещё не было ни одного стакана воды. Отметим первый?', 'happy'];
  if (hour >= 10 && mealsToday === 0) return ['pusya', 'Что было на завтрак? Запишем, пока помним.', 'happy'];
  const pools = ['plate', 'water', 'detective', 'skin', 'fun', 'fun'];
  const pool = TIPS[pools[seed % pools.length]];
  const [who, text] = pick(pool, Math.floor(seed / pools.length));
  return [who, text, who === 'medok' ? 'calm' : 'happy'];
}
